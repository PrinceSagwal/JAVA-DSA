
public class Binary_Manipulation {
    public static void main(String[] args) {
        System.out.println("Binary AND Operator: "+(5 & 6));
        System.out.println("Binary OR Operator: "+(5 | 6));
        System.out.println("Binary XOR Operator: "+(5 ^ 6));
        System.out.println("Binary One's Complement: "+(~5));
        System.out.println("Binary Left Shift: "+(5 << 2));
        System.out.println("Binary Right Shift: "+(6 >> 1));
    }
}
